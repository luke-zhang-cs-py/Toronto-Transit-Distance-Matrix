def prune(kept):
    """Delete anything left in docs/app/ from an older build.

    Without this a renamed file lives on and is still loaded, which is the
    one failure mode a generated directory has that a hand-written one does
    not.
    """
    for here, dirs, names in os.walk(OUT):
        for name in names:
            path = os.path.join(here, name)
            if os.path.relpath(path, OUT).replace("\\", "/") not in kept:
                os.remove(path)
                print("  removed stale %s" % os.path.relpath(path, OUT))


def main():
    graph = collect_graph()
    written = {}

    written["js/network-data.js"] = data_file(graph)

    for name in SHARED_JS:
        written["js/" + name] = (BANNER % ("static/js/" + name)
                                 + read(os.path.join(ROOT, "static", "js", name)))
    for name in STATIC_JS:
        written["js/" + name] = read(os.path.join(SRC, "js", name))

    written["css/style.css"] = (BANNER % "static/css/style.css"
                                + read(os.path.join(ROOT, "static", "css", "style.css")))
    written["css/static.css"] = read(os.path.join(SRC, "css", "static.css"))
    written["index.html"] = page(read(os.path.join(ROOT, "templates", "index.html")))

    for name, body in sorted(written.items()):
        write(os.path.join(OUT, name.replace("/", os.sep)), body)
    prune(set(written))

    total = sum(len(body.encode("utf-8")) for body in written.values())
    print("  %d stops, %d directed edges, %d lines"
          % (len(graph["nodes"]),
             sum(len(v) for v in graph["adj"].values()),
             len(graph["lineModes"])))
    print("  wrote %d files to docs/app (%.0f KB, %.0f KB of it the graph)"
          % (len(written), total / 1024.0,
             len(written["js/network-data.js"].encode("utf-8")) / 1024.0))


if __name__ == "__main__":
    main()
