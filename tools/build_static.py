def page(template):
    text = template

    text = replace_once(
        text,
        "<title>Toronto Transit Reach (Python)</title>",
        "<title>Toronto Transit Reach (browser build)</title>",
        "retitle the page")

    text = replace_once(
        text,
        "<link rel=\"stylesheet\" href=\"{{ url_for('static', "
        "filename='css/style.css') }}\">",
        '<link rel="stylesheet" href="css/style.css">\n'
        '<link rel="stylesheet" href="css/static.css">',
        "point the stylesheet at the copied CSS")

    text = replace_once(
        text,
        "<h1>Toronto Transit Reach<em>Python backend</em></h1>",
        "<h1>Toronto Transit Reach<em>browser build</em></h1>",
        "relabel the heading")

    text = replace_once(
        text,
        """<div class="sub">Classic OpenStreetMap tiles, no API key. Every travel time, route, and
      heat-radar point is computed by a Python routing engine over the full TTC + YRT + MiWay
      network. Click once for a start point, click again for a destination.</div>""",
        """<div class="sub">Classic OpenStreetMap tiles, no API key. Click anywhere on the map:
      every stop you can reach is shaded by how long it takes, over the full TTC + YRT + MiWay
      network. The search runs in your browser.</div>
    <div class="staticBanner">
      <b>This is the browser-only build.</b> There is no server: the whole graph is inlined in
      the page and the reachability search — a port of the same Dijkstra in
      <code>routing.py</code> — runs in JavaScript. Every wait is therefore <b>modelled</b>
      (half the typical headway for the mode running the line), not measured: GTFS-realtime
      needs a backend to fetch it, so live waits and service closures are not in this build,
      and neither is trip planning.
      <a href="%s">Run the Flask app for the live-data version →</a>
    </div>""" % REPO,
        "rewrite the standfirst and add the build banner")

    text = trip_card(text)
    text = replace_once(
        text,
        """<footer>Fixed schematic network model (TTC subway/streetcar + YRT/Viva + MiWay + highway
    corridor hubs) with typical dwell/wait/transfer times — not a live feed. All routing runs
    in the Python backend; the browser only draws the results.</footer>""",
        """<footer>Fixed schematic network model (TTC subway/streetcar + YRT/Viva + MiWay + highway
    corridor hubs) with typical dwell/wait/transfer times — not a live feed. In this build the
    routing runs in the browser, over a copy of the graph generated from the Python
    <code>network</code> package by <code>tools/build_static.py</code>; the Flask app in the
    repository is the same page with a live feed and a trip planner behind it.</footer>""",
        "rewrite the footer")

    scripts = "\n".join('<script src="%s"></script>' % name
                        for name in SCRIPT_ORDER)
    text = replace_once(
        text,
        """<script src="{{ url_for('static', filename='js/app.js') }}"></script>
  <!-- After app.js: both read map, setOrigin and planTrip from it. -->
  <script src="{{ url_for('static', filename='js/when.js') }}"></script>
  <script src="{{ url_for('static', filename='js/here.js') }}"></script>""",
        "<!-- Order matters: static-api.js installs the fetch shim before\n"
        "     app.js runs and calls it; static-ui.js replaces functions\n"
        "     app.js defines, so it goes last. when.js is absent -- it is the\n"
        "     departure-time control for the trip planner. -->\n"
        + scripts,
        "rewrite the script tags")

    left = re.findall(r"\{\{.*?\}\}|\{%.*?%\}", text)
    if left:
        raise SystemExit("build_static: unresolved Jinja left in the page: %r" % left)
    return text


def trip_card(text):
    """Swap the trip planner for a note saying where it went.

    The card itself stays in the markup, emptied and still hidden: app.js
    binds #newTripBtn at load and reads #tripCard in setOrigin, and a build
    that deletes them throws a TypeError before the map has drawn. What
    changes is that nothing ever shows it -- static-ui.js sends the second
    click back to setOrigin -- and that the note beside it is visible from
    the start rather than after a trip nobody can plan.
    """
    start = text.index('      <div class="section" id="tripCard"')
    end = text.index('      <div class="section" id="filterCard">')
    if not 0 < start < end:
        raise SystemExit("build_static: could not find the trip card in the template")

    note = """      <!-- The trip planner is not in this build. itinerary.py plans against a
           timetable index built from TTC's static GTFS, and it answers "what time
           do you arrive" -- a claim that is either right or worthless. A partial
           port would print departures nobody can catch, so it is switched off and
           says so. -->
      <div class="section" id="staticNote">
        <h2>Browser-only build</h2>
        <div class="hint"><b>Trip planning needs the local Flask app</b> — see the
          <a href="%s#run-it">README</a>. This build answers the reach
          question only: click anywhere and every stop is shaded by how long it takes
          to get there, computed here in the page.</div>
        <div class="stat"><span>Data</span><b id="liveBadge">modelled</b></div>
      </div>

      <div class="section" id="tripCard" style="display:none;">
        <div id="optionList"></div>
        <div id="tripDetail"></div>
        <button class="secondary" id="newTripBtn">Start a new trip</button>
      </div>

""" % REPO
    return text[:start] + note + text[end:]


